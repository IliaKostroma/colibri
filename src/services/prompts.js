/**
 * Обернуть пользовательский текст в разделители.
 *
 * Без этого короткая реплика вроде «Привет!» читается моделью как обращение
 * к ней самой — она начинает переспрашивать («пришлите текст подлиннее»)
 * вместо обработки. Разделители делают роль текста однозначной.
 *
 * @param {string} text
 * @returns {string}
 */
export function wrapInput(text) {
  return `<<<TEXT\n${String(text ?? '').trim()}\nTEXT>>>`;
}

/**
 * Убрать обёртку, которую модели любят добавлять вопреки инструкции:
 * кавычки вокруг всего ответа и вводную строку вида «Вот перевод:».
 * @param {string} text
 * @returns {string}
 */
export function stripModelWrapping(text) {
  if (!text) return '';

  let result = String(text).trim();

  // Вводная строка перед пустой строкой: «Вот перевод:\n\n...»
  result = result.replace(/^[^\n]{0,60}:\s*\n\s*\n/, '');

  // Кавычки вокруг всего ответа (но не внутри текста)
  const pairs = [['"', '"'], ['«', '»'], ["'", "'"], ['`', '`']];
  for (const [open, close] of pairs) {
    if (result.startsWith(open) && result.endsWith(close) && result.length > 1) {
      const inner = result.slice(open.length, -close.length);
      if (!inner.includes(close)) {
        result = inner.trim();
        break;
      }
    }
  }

  return result.trim();
}
